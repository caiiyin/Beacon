/** useTranslation hook 대신 직접 쓸 수 있는 단순 헬퍼 */
export function t(lang, key) {
  const keys = key.split(".");
  let val = translations[lang] || translations["ko"];
  for (const k of keys) {
    val = val?.[k];
  }
  return val ?? key;
}
